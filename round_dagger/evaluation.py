def evaluator_source_bundle(
    repository_root: str | Path,
    gr00t_root: str | Path,
    evaluation_source_inventory_sha256: str,
) -> dict[str, Any]:
    """Return a content manifest for every custom paired-evaluation producer.

    A hash of only ``eval_agent_trl.py`` is insufficient: the trainer hooks and
    evidence helper produce the per-view/action metrics consumed by the gate.
    This small source closure binds those producer bytes, the launcher, and the
    evidence normalizer/scorer into one deterministic identity.
    """

    roots = {
        "repository": Path(repository_root).expanduser(),
        "gr00t": Path(gr00t_root).expanduser(),
    }
    entries: list[dict[str, Any]] = []
    for root_name, paths in (
        ("repository", _REPOSITORY_EVALUATOR_SOURCES),
        ("gr00t", _GR00T_EVALUATOR_SOURCES),
    ):
        root = roots[root_name]
        if not root.is_absolute() or root.is_symlink() or not root.is_dir():
            raise EvaluationError(f"{root_name} source root is missing or unsafe")
        for relative in paths:
            source = root / relative
            if source.is_symlink() or not source.is_file():
                raise EvaluationError(
                    f"paired evaluator source is missing or unsafe: {root_name}/{relative}"
                )
            entries.append(
                {
                    "source": f"{root_name}/{relative}",
                    "sha256": sha256_file(source),
                }
            )
    inventory_sha = _sha(
        evaluation_source_inventory_sha256,
        "evaluation source inventory SHA-256",
    )
    return {
        "schema": EVALUATOR_SOURCE_BUNDLE_SCHEMA,
        "evaluation_source_inventory_sha256": inventory_sha,
        "sources": entries,
    }


def evaluator_source_bundle_sha256(
    repository_root: str | Path,
    gr00t_root: str | Path,
    evaluation_source_inventory_sha256: str,
) -> str:
    """Hash the exact paired-evaluation source bundle."""

    return canonical_json_sha256(
        evaluator_source_bundle(
            repository_root,
            gr00t_root,
            evaluation_source_inventory_sha256,
        )
    )


def _exact(value: Any, keys: set[str], label: str) -> dict[str, Any]:
    if not isinstance(value, Mapping) or set(value) != keys:
        actual = set(value) if isinstance(value, Mapping) else set()
        raise EvaluationError(
            f"{label} has missing={sorted(keys - actual)} unknown={sorted(actual - keys)}"
        )
    return dict(value)


def _sha(value: Any, label: str) -> str:
    if not isinstance(value, str) or _SHA_RE.fullmatch(value) is None:
        raise EvaluationError(f"{label} must be a lowercase SHA-256")
    return value


def _integer(value: Any, label: str, *, minimum: int = 0) -> int:
    if type(value) is not int or value < minimum:
        raise EvaluationError(f"{label} must be an integer >= {minimum}")
    return value


def _number(value: Any, label: str, *, minimum: float | None = None) -> float:
    if isinstance(value, bool):
        raise EvaluationError(f"{label} must be a finite number")
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise EvaluationError(f"{label} must be a finite number") from exc
    if not math.isfinite(result) or (minimum is not None and result < minimum):
        raise EvaluationError(f"{label} must be finite and >= {minimum}")
    return result


def _token(value: Any, label: str) -> str:
    if not isinstance(value, str) or _TOKEN_RE.fullmatch(value) is None:
        raise EvaluationError(f"{label} must be a safe token")
    return value


def _evaluation_root_for_contract(
    root: Path, contract_path: str | Path, macro_round: int
) -> Path:
    """Return the only allowed root for canonical or hardened-recovery eval.

    Normal orchestration owns ``evaluation/``.  A source-hardening recovery is
    deliberately isolated below a deterministic ``evaluation_recovery``
    namespace so an older immutable result is never renamed, removed, or
    overwritten.  No other redirect is accepted.
    """

    path = Path(contract_path)
    if not path.is_absolute():
        path = root / path
    path = Path(os.path.abspath(path))
    round_root = root / "rounds" / f"macro_round_{macro_round:06d}"
    canonical = round_root / "evaluation" / "contract.json"
    if path == canonical:
        return canonical.parent
    try:
        relative = path.relative_to(round_root / "evaluation_recovery")
    except ValueError as exc:
        raise EvaluationError("evaluation contract path is non-canonical") from exc
    if (
        len(relative.parts) != 2
        or _RECOVERY_ID_RE.fullmatch(relative.parts[0]) is None
        or relative.parts[1] != "contract.json"
    ):
        raise EvaluationError("hardened recovery contract path is non-canonical")
    return path.parent


def _validate_thresholds(value: Mapping[str, Any] | None) -> dict[str, Any]:
    raw = dict(DEFAULT_THRESHOLDS if value is None else value)
    expected = set(DEFAULT_THRESHOLDS)
    thresholds = _exact(raw, expected, "paired evaluation thresholds")
    thresholds["minimum_paired_cases"] = _integer(
        thresholds["minimum_paired_cases"], "minimum_paired_cases", minimum=1
    )
    for key in expected - {"minimum_paired_cases", "allow_bounded_nonregression"}:
        thresholds[key] = _number(thresholds[key], key, minimum=0.0)
    if type(thresholds["allow_bounded_nonregression"]) is not bool:
        raise EvaluationError("allow_bounded_nonregression must be boolean")
    for key in (
        "minimum_success_rate_improvement",
        "minimum_safety_rate_improvement",
        "maximum_success_rate_regression",
        "maximum_safety_violation_rate_regression",
    ):
        if thresholds[key] > 1.0:
            raise EvaluationError(f"{key} must be <= 1")
    if thresholds["action_mse_floor"] <= 0.0:
        raise EvaluationError("action_mse_floor must be positive")
    return thresholds


_CASE_KEYS = {"seed", "env_index", "scenario_id"}


def _validate_cases(value: Any) -> list[dict[str, Any]]:
    if not isinstance(value, list) or not value:
        raise EvaluationError("scenario_cases must be a non-empty list")
    cases: list[dict[str, Any]] = []
    identities: set[tuple[int, int]] = set()
    for index, raw in enumerate(value):
        case = _exact(raw, _CASE_KEYS, f"scenario_cases[{index}]")
        seed = _integer(case["seed"], "case.seed")
        env_index = _integer(case["env_index"], "case.env_index")
        scenario_id = _sha(case["scenario_id"], "case.scenario_id")
        identity = (seed, env_index)
        if identity in identities:
            raise EvaluationError("scenario_cases contain duplicate seed/env identity")
        identities.add(identity)
        cases.append({"seed": seed, "env_index": env_index, "scenario_id": scenario_id})
    cases.sort(key=lambda item: (item["seed"], item["env_index"]))
    seeds = sorted({item["seed"] for item in cases})
    if len(seeds) < 2:
        raise EvaluationError("paired evaluation requires at least two explicit seeds")
    expected_envs: list[int] | None = None
    for seed in seeds:
        envs = [item["env_index"] for item in cases if item["seed"] == seed]
        if envs != list(range(len(envs))):
            raise EvaluationError(
                "each seed must cover contiguous env_index values 0..N-1"
            )
        if expected_envs is None:
            expected_envs = envs
        elif envs != expected_envs:
            raise EvaluationError("every seed must cover the same environment indices")
    return cases


