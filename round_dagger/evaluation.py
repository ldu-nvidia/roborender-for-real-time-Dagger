def _validate_policy(value: Any, role: str) -> dict[str, Any]:
    policy = _exact(value, _POLICY_KEYS, f"{role} policy")
    if policy["role"] != role:
        raise EvaluationError(f"policy role must be {role}")
    _integer(policy["version"], f"{role}.version")
    if not isinstance(policy["checkpoint_path"], str) or not policy["checkpoint_path"]:
        raise EvaluationError(f"{role}.checkpoint_path is missing")
    for key in ("checkpoint_sha256", "manifest_sha256", "runtime_policy_sha256"):
        _sha(policy[key], f"{role}.{key}")
    return policy


def create_contract(
    root: str | Path,
    *,
    candidate_manifest: str | Path,
    scenario_cases: Sequence[Mapping[str, Any]],
    parent_runtime_policy_sha256: str,
    candidate_runtime_policy_sha256: str,
    renderer_runtime_sha256: str,
    evaluation_config_sha256: str,
    evaluator_code_sha256: str,
    expected_renderer_count: int,
    anchor_pool_path: str | Path,
    anchor_count: int,
    anchor_index: int,
    anchor_inventory_sha256: str,
    output: str | Path,
    thresholds: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Publish an immutable parent/candidate paired-evaluation contract."""

    root = _campaign_root(root)
    state = load_state(root)
    if state["phase"] != "TRAINED":
        raise EvaluationError("paired evaluation contract requires TRAINED state")
    campaign = load_campaign(root)
    candidate = load_candidate_manifest(
        root,
        candidate_manifest,
        expected_macro_round=state["open_macro_round"],
        bind_state=True,
    )
    cases = _validate_cases([dict(item) for item in scenario_cases])
    seeds = sorted({item["seed"] for item in cases})
    envs_per_seed = len([item for item in cases if item["seed"] == seeds[0]])
    active = state["active_policy"]
    policies = [
        {
            "role": "parent",
            "version": active["version"],
            "checkpoint_path": active["checkpoint_path"],
            "checkpoint_sha256": active["checkpoint_sha256"],
            "manifest_sha256": active["manifest_sha256"],
            "runtime_policy_sha256": _sha(
                parent_runtime_policy_sha256, "parent_runtime_policy_sha256"
            ),
        },
        {
            "role": "candidate",
            "version": candidate["policy_version"],
            "checkpoint_path": candidate["checkpoint_path"],
            "checkpoint_sha256": candidate["checkpoint_sha256"],
            "manifest_sha256": candidate["manifest_sha256"],
            "runtime_policy_sha256": _sha(
                candidate_runtime_policy_sha256, "candidate_runtime_policy_sha256"
            ),
        },
    ]
    runtime = {
        "policy_views": list(POLICY_VIEWS),
        "view_layout": "vertical",
        "raytraced_mix_prob": RAYTRACED_MIX,
        "reference_lag": REFERENCE_LAG,
        "training_enabled": False,
        "one_episode_per_environment": True,
    }
    anchor_path = Path(anchor_pool_path)
    if (
        not anchor_path.is_absolute()
        or any(part in {".", ".."} for part in anchor_path.parts)
    ):
        raise EvaluationError("anchor pool path must be normalized and absolute")
    normalized_anchor_count = _integer(anchor_count, "anchor_count", minimum=1)
    normalized_anchor_index = _integer(anchor_index, "anchor_index")
    if normalized_anchor_index >= normalized_anchor_count:
        raise EvaluationError("anchor_index must be smaller than anchor_count")
    anchor_pool = {
        "path": str(anchor_path),
        "anchor_count": normalized_anchor_count,
        "anchor_index": normalized_anchor_index,
        "inventory_sha256": _sha(
            anchor_inventory_sha256,
            "anchor_inventory_sha256",
        ),
    }
    production = campaign.get("schema") == PRODUCTION_CAMPAIGN_SCHEMA
    contract = {
        "schema": PRODUCTION_CONTRACT_SCHEMA if production else CONTRACT_SCHEMA,
        "campaign_id": campaign["campaign_id"],
        "campaign_sha256": canonical_json_sha256(campaign),
        "macro_round": state["open_macro_round"],
        "candidate_manifest_path": candidate["manifest_path"],
        "candidate_manifest_sha256": candidate["manifest_sha256"],
        "policies": policies,
        "renderer_sha256": campaign["renderer_sha256"],
        "renderer_runtime_sha256": _sha(
            renderer_runtime_sha256, "renderer_runtime_sha256"
        ),
        "camera_mapping_sha256": campaign["camera_mapping_sha256"],
        "evaluation_config_sha256": _sha(
            evaluation_config_sha256, "evaluation_config_sha256"
        ),
        "evaluator_code_sha256": _sha(evaluator_code_sha256, "evaluator_code_sha256"),
        "expected_renderer_count": _integer(
            expected_renderer_count, "expected_renderer_count", minimum=1
        ),
        "anchor_pool": anchor_pool,
        "runtime": runtime,
        "seeds": seeds,
        "num_envs_per_seed": envs_per_seed,
        "scenario_cases": cases,
        "thresholds": _validate_thresholds(thresholds),
    }
    if production:
        contract["data_lineage"] = campaign["data_lineage"]
        contract["data_lineage_sha256"] = campaign["data_lineage_sha256"]
    _validate_contract_document(root, contract, bind_state=True)
    output_path, relative = _internal_path(root, output, "evaluation contract")
    _evaluation_root_for_contract(root, output_path, contract["macro_round"])
    digest = publish_immutable_json(output_path, contract)
    return {**contract, "contract_path": relative, "contract_sha256": digest}


def _validate_contract_document(
    root: Path, document: Any, *, bind_state: bool
) -> dict[str, Any]:
    if not isinstance(document, Mapping):
        raise EvaluationError("paired evaluation contract must be a mapping")
    schema = document.get("schema")
    campaign = load_campaign(root)
    production_campaign = campaign.get("schema") == PRODUCTION_CAMPAIGN_SCHEMA
    if schema == PRODUCTION_CONTRACT_SCHEMA:
        contract = _exact(
            document,
            _PRODUCTION_CONTRACT_KEYS,
            "production paired evaluation contract",
        )
    elif schema == CONTRACT_SCHEMA:
        contract = _exact(document, _CONTRACT_KEYS, "paired evaluation contract")
    elif schema == LEGACY_CONTRACT_SCHEMA:
        contract = _exact(
            document,
            _LEGACY_CONTRACT_KEYS,
            "legacy paired evaluation contract",
        )
    else:
        raise EvaluationError("paired evaluation contract schema mismatch")
    if production_campaign != (schema == PRODUCTION_CONTRACT_SCHEMA):
        raise EvaluationError(
            "production campaign requires capture-bound evaluation contract v3"
        )
    if contract["campaign_id"] != campaign["campaign_id"] or contract[
        "campaign_sha256"
    ] != canonical_json_sha256(campaign):
        raise EvaluationError("evaluation contract belongs to another campaign")
    _integer(contract["macro_round"], "macro_round")
    for key in (
        "candidate_manifest_sha256",
        "renderer_sha256",
        "renderer_runtime_sha256",
        "camera_mapping_sha256",
        "evaluation_config_sha256",
        "evaluator_code_sha256",
    ):
        _sha(contract[key], key)
    if contract["renderer_sha256"] != campaign["renderer_sha256"]:
        raise EvaluationError("renderer package SHA differs from campaign")
    if contract["camera_mapping_sha256"] != campaign["camera_mapping_sha256"]:
        raise EvaluationError("camera mapping SHA differs from campaign")
    policies = contract["policies"]
    if not isinstance(policies, list) or len(policies) != 2:
        raise EvaluationError("contract must contain parent and candidate policies")
    parent = _validate_policy(policies[0], "parent")
    candidate_policy = _validate_policy(policies[1], "candidate")
    candidate = load_candidate_manifest(
        root,
        contract["candidate_manifest_path"],
        expected_macro_round=contract["macro_round"],
        bind_state=bind_state,
    )
    if contract["candidate_manifest_sha256"] != candidate["manifest_sha256"]:
        raise EvaluationError("candidate manifest SHA mismatch")
    expected_candidate = {
        "version": candidate["policy_version"],
        "checkpoint_path": candidate["checkpoint_path"],
        "checkpoint_sha256": candidate["checkpoint_sha256"],
        "manifest_sha256": candidate["manifest_sha256"],
    }
    if any(candidate_policy[key] != value for key, value in expected_candidate.items()):
        raise EvaluationError("candidate policy identity mismatch")
    state = load_state(root)
    active = state["active_policy"]
    expected_parent = {
        "version": active["version"],
        "checkpoint_path": active["checkpoint_path"],
        "checkpoint_sha256": active["checkpoint_sha256"],
        "manifest_sha256": active["manifest_sha256"],
    }
    # During an idempotent recovery retry the candidate has already become the
    # active policy, so the historical parent cannot still equal active_policy.
    # The caller disables mutable-state binding in that narrow READY retry;
    # immutable policy identities and checkpoint bytes remain verified below.
    if bind_state and any(parent[key] != value for key, value in expected_parent.items()):
        raise EvaluationError("parent policy identity mismatch")
    for policy in (parent, candidate_policy):
        checkpoint, _ = _internal_path(
            root, policy["checkpoint_path"], "policy checkpoint"
        )
        if sha256_file(checkpoint) != policy["checkpoint_sha256"]:
            raise EvaluationError(f"{policy['role']} checkpoint changed")
    expected_runtime = {
        "policy_views": list(POLICY_VIEWS),
        "view_layout": "vertical",
        "raytraced_mix_prob": RAYTRACED_MIX,
        "reference_lag": REFERENCE_LAG,
        "training_enabled": False,
        "one_episode_per_environment": True,
    }
    if contract["runtime"] != expected_runtime:
        raise EvaluationError(
            "evaluation runtime is not generated-only 3-view lag-256 eval"
        )
    cases = _validate_cases(contract["scenario_cases"])
    if cases != contract["scenario_cases"]:
        raise EvaluationError("scenario cases are not in canonical order")
    seeds = sorted({item["seed"] for item in cases})
    if contract["seeds"] != seeds:
        raise EvaluationError("contract seeds differ from scenario cases")
    envs = len([item for item in cases if item["seed"] == seeds[0]])
    if contract["num_envs_per_seed"] != envs:
        raise EvaluationError("num_envs_per_seed differs from scenario cases")
    _integer(contract["expected_renderer_count"], "expected_renderer_count", minimum=1)
    if contract["schema"] in {CONTRACT_SCHEMA, PRODUCTION_CONTRACT_SCHEMA}:
        anchor = _exact(
            contract["anchor_pool"],
            _ANCHOR_POOL_KEYS,
            "evaluation anchor pool",
        )
        anchor_path = Path(anchor["path"])
        if (
            not isinstance(anchor["path"], str)
            or not anchor_path.is_absolute()
            or any(part in {".", ".."} for part in anchor_path.parts)
        ):
            raise EvaluationError("evaluation anchor pool path is unsafe")
        validated_anchor_count = _integer(
            anchor["anchor_count"], "anchor_count", minimum=1
        )
        validated_anchor_index = _integer(anchor["anchor_index"], "anchor_index")
        if validated_anchor_index >= validated_anchor_count:
            raise EvaluationError("anchor_index must be smaller than anchor_count")
        _sha(anchor["inventory_sha256"], "anchor inventory SHA-256")
    if production_campaign:
        try:
            lineage = validate_data_lineage(contract["data_lineage"])
            lineage_sha = data_lineage_sha256(lineage)
        except ProductionDataLineageError as exc:
            raise EvaluationError(f"evaluation data lineage is invalid: {exc}") from exc
        if (
            lineage != campaign["data_lineage"]
            or lineage_sha != campaign["data_lineage_sha256"]
            or contract["data_lineage_sha256"] != lineage_sha
        ):
            raise EvaluationError("evaluation data lineage differs from campaign")
        scenario_payload = (
            json.dumps(
                contract["scenario_cases"],
                sort_keys=True,
                separators=(",", ":"),
                ensure_ascii=True,
                allow_nan=False,
            ).encode("utf-8")
            + b"\n"
        )
        if hashlib.sha256(scenario_payload).hexdigest() != lineage[
            "heldout_evaluation"
        ]["scenario_contract_sha256"]:
            raise EvaluationError(
                "evaluation scenarios differ from live capture attestation"
            )
        if len(contract["scenario_cases"]) != 256:
            raise EvaluationError("production evaluation must contain 256 cases")
    contract["thresholds"] = _validate_thresholds(contract["thresholds"])
    return contract


def load_contract(
    root: str | Path, path: str | Path, *, bind_state: bool = True
) -> dict[str, Any]:
    root = _campaign_root(root)
    contract_path, relative = _internal_path(root, path, "evaluation contract")
    contract = _validate_contract_document(
        root, load_strict_json(contract_path), bind_state=bind_state
    )
    return {
        **contract,
        "contract_path": relative,
        "contract_sha256": sha256_file(contract_path),
    }


def _selected_renderer_rows(
    snapshot: Mapping[str, Any], expected: int
) -> list[dict[str, Any]]:
    rows = snapshot.get("selected")
    if not isinstance(rows, list) or len(rows) != expected:
        raise EvaluationError(
            f"renderer snapshot must contain exactly {expected} selected endpoints"
        )
    normalized: dict[str, dict[str, Any]] = {}
    for raw in rows:
        if not isinstance(raw, Mapping) or not isinstance(raw.get("file"), str):
            raise EvaluationError("renderer snapshot row is malformed")
        if raw["file"] in normalized:
            raise EvaluationError("renderer endpoint identity is duplicated")
        normalized[raw["file"]] = dict(raw)
    return [normalized[key] for key in sorted(normalized)]


def _renderer_delta(
    before: Mapping[str, Any], after: Mapping[str, Any], contract: Mapping[str, Any]
) -> tuple[int, str]:
    expected = contract["expected_renderer_count"]
    old_rows = _selected_renderer_rows(before, expected)
    new_rows = _selected_renderer_rows(after, expected)
    if [row["file"] for row in old_rows] != [row["file"] for row in new_rows]:
        raise EvaluationError("renderer fleet changed during evaluation")
    requests = 0
    identity_digest: str | None = None
    server_ids: set[str] = set()
    for old, new in zip(old_rows, new_rows, strict=True):
        old_response, new_response = old.get("response"), new.get("response")
        if not isinstance(old_response, Mapping) or not isinstance(
            new_response, Mapping
        ):
            raise EvaluationError("renderer response is malformed")
        identity = old_response.get("runtime_identity")
        if not isinstance(identity, Mapping) or identity != new_response.get(
            "runtime_identity"
        ):
            raise EvaluationError("renderer runtime identity changed")
        current_digest = canonical_json_sha256(identity)
        if current_digest != contract["renderer_runtime_sha256"]:
            raise EvaluationError("renderer runtime hash differs from contract")
        if identity_digest is None:
            identity_digest = current_digest
        elif identity_digest != current_digest:
            raise EvaluationError("renderer fleet has mixed runtime identities")
        server_id = old_response.get("server_id")
        if not isinstance(server_id, str) or server_id != new_response.get("server_id"):
            raise EvaluationError("renderer server identity changed")
        server_ids.add(server_id)
        old_metrics, new_metrics = (
            old_response.get("metrics"),
            new_response.get("metrics"),
        )
        if not isinstance(old_metrics, Mapping) or not isinstance(new_metrics, Mapping):
            raise EvaluationError("renderer counters are missing")
        old_requests = _integer(old_metrics.get("requests"), "before renderer requests")
        new_requests = _integer(new_metrics.get("requests"), "after renderer requests")
        for name in ("errors", "replays"):
            if _integer(old_metrics.get(name), f"before renderer {name}") != 0:
                raise EvaluationError(f"renderer fleet has nonzero {name}")
            if _integer(new_metrics.get(name), f"after renderer {name}") != 0:
                raise EvaluationError(f"renderer fleet has nonzero {name}")
        if new_requests < old_requests:
            raise EvaluationError("renderer request counter moved backwards")
        requests += new_requests - old_requests
    if len(server_ids) != expected or identity_digest is None or requests <= 0:
        raise EvaluationError("renderer fleet identity/traffic evidence is incomplete")
    return requests, identity_digest


