def _policy_for_role(contract: Mapping[str, Any], role: str) -> dict[str, Any]:
    if role not in {"parent", "candidate"}:
        raise EvaluationError("role must be parent or candidate")
    return next(dict(item) for item in contract["policies"] if item["role"] == role)


def evaluation_run_id(
    contract: Mapping[str, Any], *, role: str, seed: int, attempt: int
) -> str:
    """Return the canonical Image3F stream namespace for one eval attempt.

    A retry must never reuse the failed attempt's namespace: Image3F servers
    retain ordered per-stream state, so reusing it would make the new step zero
    look like a replay or an out-of-order request.  The immutable contract,
    policy role, seed, and monotonically allocated attempt are all encoded.
    """

    contract_sha = _sha(contract.get("contract_sha256"), "contract SHA")
    if role not in {"parent", "candidate"}:
        raise EvaluationError("role must be parent or candidate")
    seed = _integer(seed, "seed")
    attempt = _integer(attempt, "attempt", minimum=1)
    run_id = f"rde-{contract_sha[:20]}-{role}-s{seed}-a{attempt:06d}"
    if _TOKEN_RE.fullmatch(run_id) is None:
        raise EvaluationError("derived Image3F run ID is not a safe token")
    return run_id


def _validate_evaluation_run_id(
    value: Any, contract: Mapping[str, Any], *, role: str, seed: int
) -> str:
    if not isinstance(value, str) or _TOKEN_RE.fullmatch(value) is None:
        raise EvaluationError("Image3F run ID is not a safe runtime token")
    prefix = evaluation_run_id(contract, role=role, seed=seed, attempt=1).rsplit(
        "-a", 1
    )[0]
    match = re.fullmatch(re.escape(prefix) + r"-a([0-9]{6,})", value)
    if match is None:
        raise EvaluationError(
            "Image3F run ID is not bound to the contract, role, and seed"
        )
    attempt = int(match.group(1))
    if value != evaluation_run_id(contract, role=role, seed=seed, attempt=attempt):
        raise EvaluationError("Image3F run ID has a non-canonical attempt number")
    return value


def attest_outcome(
    root: str | Path,
    *,
    contract_path: str | Path,
    role: str,
    seed: int,
    metrics_path: str | Path,
    renderer_before_path: str | Path,
    renderer_after_path: str | Path,
    image3f_run_id: str,
    output: str | Path,
) -> dict[str, Any]:
    """Normalize one seed block after strict runtime and renderer validation."""

    root = _campaign_root(root)
    contract = load_contract(root, contract_path)
    if contract["schema"] not in {CONTRACT_SCHEMA, PRODUCTION_CONTRACT_SCHEMA}:
        raise EvaluationError("legacy evaluation contracts are diagnostic-only")
    seed = _integer(seed, "seed")
    if seed not in contract["seeds"]:
        raise EvaluationError("seed is not in the immutable evaluation contract")
    policy = _policy_for_role(contract, role)
    image3f_run_id = _validate_evaluation_run_id(
        image3f_run_id, contract, role=role, seed=seed
    )
    metrics_file, metrics_relative = _internal_path(
        root, metrics_path, "evaluation metrics"
    )
    before_file, before_relative = _internal_path(
        root, renderer_before_path, "renderer before snapshot"
    )
    after_file, after_relative = _internal_path(
        root, renderer_after_path, "renderer after snapshot"
    )
    metrics = load_strict_json(metrics_file)
    before = load_strict_json(before_file)
    after = load_strict_json(after_file)
    if (
        not isinstance(metrics, Mapping)
        or not isinstance(before, Mapping)
        or not isinstance(after, Mapping)
    ):
        raise EvaluationError("metrics and renderer snapshots must be JSON mappings")
    served_requests, runtime_digest = _renderer_delta(before, after, contract)

    adapter = metrics.get("_roborender_eval_adapter")
    if not isinstance(adapter, Mapping) or adapter.get("schema_version") != 1:
        raise EvaluationError("metrics lack the fail-closed evaluator adapter marker")
    if adapter.get("image3f_run_id") != image3f_run_id:
        raise EvaluationError(
            "evaluator metrics do not attest the intended Image3F run ID"
        )
    runtime = metrics.get("_roborender_paired_evaluation")
    expected_runtime = {
        "schema": RUNTIME_SCHEMA,
        "eval_relabel_enabled": True,
        "policy_views": list(POLICY_VIEWS),
        "view_layout": "vertical",
        "raytraced_mix_prob": RAYTRACED_MIX,
        "reference_lag": REFERENCE_LAG,
        "training_enabled": False,
        "one_episode_per_environment": True,
        "generation_seed": seed,
        "runtime_policy_sha256": policy["runtime_policy_sha256"],
        "evaluation_config_sha256": contract["evaluation_config_sha256"],
        "evaluator_code_sha256": contract["evaluator_code_sha256"],
    }
    if runtime != expected_runtime:
        raise EvaluationError("evaluator runtime evidence differs from paired contract")
    generated_steps = _integer(
        metrics.get("generated_policy_steps"), "generated_policy_steps", minimum=1
    )
    generated_frames = _integer(
        metrics.get("generated_frames"), "generated_frames", minimum=1
    )
    if generated_frames != served_requests:
        raise EvaluationError(
            "generated frame count differs from renderer request delta"
        )

    expected_cases = [
        item for item in contract["scenario_cases"] if item["seed"] == seed
    ]
    if generated_frames != generated_steps * len(expected_cases):
        raise EvaluationError(
            "generated frame count is not one three-view request per environment step"
        )

    image3f_runtime = _exact(
        metrics.get("_roborender_image3f_eval"),
        _IMAGE3F_RUNTIME_KEYS,
        "Image3F runtime evidence",
    )
    expected_image3f_runtime = {
        "schema": "fast_roborender.image3f_fixed_eval_runtime.v1",
        "eval_relabel_enabled": True,
        "raytraced_mix_prob": RAYTRACED_MIX,
        "reference_lag": REFERENCE_LAG,
        "generation_seed": seed,
        "policy_views": list(POLICY_VIEWS),
        "generated_policy_steps": generated_steps,
        "generated_frames": generated_frames,
    }
    if any(
        image3f_runtime.get(key) != value
        for key, value in expected_image3f_runtime.items()
    ):
        raise EvaluationError(
            "Image3F runtime evidence differs from paired evaluation counters/config"
        )
    expected_env_keys = {str(index) for index in range(len(expected_cases))}
    condition_hashes = image3f_runtime["first_condition_sha256_by_env"]
    generated_hashes = image3f_runtime["first_generated_sha256_by_env"]
    if (
        not isinstance(condition_hashes, Mapping)
        or set(condition_hashes) != expected_env_keys
        or not isinstance(generated_hashes, Mapping)
        or set(generated_hashes) != expected_env_keys
    ):
        raise EvaluationError(
            "Image3F first-condition/generated identity coverage is incomplete"
        )
    condition_hashes = {
        key: _sha(value, f"first condition SHA for env {key}")
        for key, value in condition_hashes.items()
    }
    generated_hashes = {
        key: _sha(value, f"first generated SHA for env {key}")
        for key, value in generated_hashes.items()
    }

    fixed_records = metrics.get("_roborender_fixed_seed_episodes")
    if not isinstance(fixed_records, list) or len(fixed_records) != len(expected_cases):
        raise EvaluationError("fixed-seed first-condition evidence is incomplete")
    fixed_by_env: dict[int, dict[str, Any]] = {}
    for raw in fixed_records:
        record = _exact(raw, _FIXED_EPISODE_KEYS, "fixed-seed episode")
        env_index = _integer(record["env_index"], "fixed episode.env_index")
        if env_index >= len(expected_cases) or env_index in fixed_by_env:
            raise EvaluationError("fixed-seed episode env_index coverage is ambiguous")
        if _integer(record["seed"], "fixed episode.seed") != seed:
            raise EvaluationError("fixed-seed episode seed mismatch")
        if type(record["success"]) is not bool:
            raise EvaluationError("fixed-seed episode success must be boolean")
        _number(record["reward"], "fixed episode.reward")
        _integer(record["episode_length"], "fixed episode.episode_length", minimum=1)
        if record["object_class"] is not None and not isinstance(
            record["object_class"], str
        ):
            raise EvaluationError("fixed-seed episode object_class is malformed")
        condition_sha = _sha(
            record["first_condition_sha256"], "fixed episode first condition SHA"
        )
        generated_sha = _sha(
            record["first_generated_sha256"], "fixed episode first generated SHA"
        )
        if (
            condition_sha != condition_hashes[str(env_index)]
            or generated_sha != generated_hashes[str(env_index)]
        ):
            raise EvaluationError(
                "fixed-seed episode condition/generated identity differs from Image3F runtime"
            )
        scenario_payload = {
            "seed": seed,
            "env_index": env_index,
            "first_condition_sha256": condition_sha,
        }
        if _sha(record["scenario_id"], "fixed episode scenario_id") != canonical_json_sha256(
            scenario_payload
        ):
            raise EvaluationError(
                "fixed-seed scenario identity is not derived from its initial condition"
            )
        fixed_by_env[env_index] = record

    raw_episodes = metrics.get("_roborender_paired_episodes")
    if not isinstance(raw_episodes, list) or len(raw_episodes) != len(expected_cases):
        raise EvaluationError("per-environment outcome evidence is incomplete")
    by_env: dict[int, dict[str, Any]] = {}
    for raw in raw_episodes:
        episode = _exact(raw, _RAW_PAIRED_EPISODE_KEYS, "paired episode")
        env_index = _integer(episode["env_index"], "episode.env_index")
        if env_index in by_env:
            raise EvaluationError(
                "per-environment outcomes contain duplicate env_index"
            )
        if _integer(episode["seed"], "episode.seed") != seed:
            raise EvaluationError("episode seed mismatch")
        _sha(episode["scenario_id"], "episode.scenario_id")
        if (
            type(episode["success"]) is not bool
            or type(episode["safety_violation"]) is not bool
        ):
            raise EvaluationError("episode success/safety fields must be boolean")
        episode["action_imitation_mse"] = _number(
            episode["action_imitation_mse"], "episode.action_imitation_mse", minimum=0.0
        )
        _integer(episode["episode_length"], "episode.episode_length", minimum=1)
        views = _exact(
            episode["generated_view_sha256"], set(POLICY_VIEWS), "generated_view_sha256"
        )
        for view in POLICY_VIEWS:
            _sha(views[view], f"generated {view} SHA")
        fixed = fixed_by_env.get(env_index)
        if fixed is None or any(
            fixed[key] != episode[key]
            for key in (
                "seed",
                "env_index",
                "scenario_id",
                "success",
                "episode_length",
            )
        ):
            raise EvaluationError(
                "paired episode differs from fixed-seed reset/outcome evidence"
            )
        episode["first_condition_sha256"] = condition_hashes[str(env_index)]
        episode["first_generated_sha256"] = generated_hashes[str(env_index)]
        by_env[env_index] = episode
    episodes = [
        by_env[index] for index in range(len(expected_cases)) if index in by_env
    ]
    if len(episodes) != len(expected_cases):
        raise EvaluationError("episode env_index coverage is not exactly 0..N-1")
    for expected, actual in zip(expected_cases, episodes, strict=True):
        if (
            actual["env_index"] != expected["env_index"]
            or actual["scenario_id"] != expected["scenario_id"]
        ):
            raise EvaluationError(
                "runtime scenario identity differs from paired contract"
            )
    if generated_steps < max(item["episode_length"] for item in episodes):
        raise EvaluationError(
            "generated policy-step count is shorter than a completed first episode"
        )
    if not any(item["episode_length"] > REFERENCE_LAG for item in episodes):
        raise EvaluationError(
            "no first episode crossed the lag-256 generated-reference boundary"
        )

    source_artifacts = {
        "metrics_path": metrics_relative,
        "metrics_sha256": sha256_file(metrics_file),
        "renderer_before_path": before_relative,
        "renderer_before_sha256": sha256_file(before_file),
        "renderer_after_path": after_relative,
        "renderer_after_sha256": sha256_file(after_file),
    }
    production = contract["schema"] == PRODUCTION_CONTRACT_SCHEMA
    outcome = {
        "schema": PRODUCTION_OUTCOME_SCHEMA if production else OUTCOME_SCHEMA,
        "contract_sha256": contract["contract_sha256"],
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "role": role,
        "seed": seed,
        "policy_version": policy["version"],
        "policy_checkpoint_sha256": policy["checkpoint_sha256"],
        "runtime_policy_sha256": policy["runtime_policy_sha256"],
        "renderer_sha256": contract["renderer_sha256"],
        "renderer_runtime_sha256": runtime_digest,
        "evaluation_config_sha256": contract["evaluation_config_sha256"],
        "evaluator_code_sha256": contract["evaluator_code_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "image3f_run_id": image3f_run_id,
        "runtime": contract["runtime"],
        "renderer_errors": 0,
        "renderer_replays": 0,
        "served_requests": served_requests,
        "generated_policy_steps": generated_steps,
        "generated_frames": generated_frames,
        "episodes": episodes,
        "source_artifacts": source_artifacts,
    }
    if production:
        outcome["data_lineage_sha256"] = contract["data_lineage_sha256"]
    output_path, relative = _internal_path(root, output, "paired outcome")
    digest = publish_immutable_json(output_path, outcome)
    return {**outcome, "outcome_path": relative, "outcome_sha256": digest}


def load_outcome(
    root: str | Path,
    path: str | Path,
    *,
    contract: Mapping[str, Any],
    expected_role: str,
    expected_seed: int,
    expected_attempt: int | None = None,
) -> dict[str, Any]:
    root = _campaign_root(root)
    outcome_path, relative = _internal_path(root, path, "paired outcome")
    production = contract["schema"] == PRODUCTION_CONTRACT_SCHEMA
    outcome = _exact(
        load_strict_json(outcome_path),
        _PRODUCTION_OUTCOME_KEYS if production else _OUTCOME_KEYS,
        "paired outcome",
    )
    expected_schema = PRODUCTION_OUTCOME_SCHEMA if production else OUTCOME_SCHEMA
    if outcome["schema"] != expected_schema:
        raise EvaluationError("paired outcome schema mismatch")
    policy = _policy_for_role(contract, expected_role)
    expected = {
        "contract_sha256": contract["contract_sha256"],
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "role": expected_role,
        "seed": expected_seed,
        "policy_version": policy["version"],
        "policy_checkpoint_sha256": policy["checkpoint_sha256"],
        "runtime_policy_sha256": policy["runtime_policy_sha256"],
        "renderer_sha256": contract["renderer_sha256"],
        "renderer_runtime_sha256": contract["renderer_runtime_sha256"],
        "evaluation_config_sha256": contract["evaluation_config_sha256"],
        "evaluator_code_sha256": contract["evaluator_code_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "runtime": contract["runtime"],
        "renderer_errors": 0,
        "renderer_replays": 0,
    }
    if production:
        expected["data_lineage_sha256"] = contract["data_lineage_sha256"]
    if any(outcome.get(key) != value for key, value in expected.items()):
        raise EvaluationError("paired outcome identity/provenance mismatch")
    image3f_run_id = _validate_evaluation_run_id(
        outcome["image3f_run_id"],
        contract,
        role=expected_role,
        seed=expected_seed,
    )
    if expected_attempt is not None:
        expected_attempt = _integer(expected_attempt, "expected attempt", minimum=1)
        if image3f_run_id != evaluation_run_id(
            contract,
            role=expected_role,
            seed=expected_seed,
            attempt=expected_attempt,
        ):
            raise EvaluationError(
                "paired outcome run ID differs from its immutable attempt directory"
            )
    _integer(outcome["served_requests"], "served_requests", minimum=1)
    _integer(outcome["generated_policy_steps"], "generated_policy_steps", minimum=1)
    if (
        _integer(outcome["generated_frames"], "generated_frames", minimum=1)
        != outcome["served_requests"]
    ):
        raise EvaluationError("outcome generated/served frame count mismatch")
    sources = _exact(outcome["source_artifacts"], _SOURCE_KEYS, "source_artifacts")
    for prefix in ("metrics", "renderer_before", "renderer_after"):
        source, _ = _internal_path(root, sources[f"{prefix}_path"], f"{prefix} source")
        if sha256_file(source) != _sha(sources[f"{prefix}_sha256"], f"{prefix} SHA"):
            raise EvaluationError(f"{prefix} source artifact changed")
    expected_cases = [
        item for item in contract["scenario_cases"] if item["seed"] == expected_seed
    ]
    episodes = outcome["episodes"]
    if not isinstance(episodes, list) or len(episodes) != len(expected_cases):
        raise EvaluationError("outcome episode coverage is incomplete")
    for expected_case, raw in zip(expected_cases, episodes, strict=True):
        episode = _exact(raw, _EPISODE_KEYS, "outcome episode")
        if (
            episode["env_index"] != expected_case["env_index"]
            or episode["seed"] != expected_seed
            or episode["scenario_id"] != expected_case["scenario_id"]
        ):
            raise EvaluationError("outcome scenario pairing mismatch")
        if (
            type(episode["success"]) is not bool
            or type(episode["safety_violation"]) is not bool
        ):
            raise EvaluationError("outcome success/safety fields are malformed")
        _number(episode["action_imitation_mse"], "action_imitation_mse", minimum=0.0)
        _integer(episode["episode_length"], "episode_length", minimum=1)
        views = _exact(
            episode["generated_view_sha256"], set(POLICY_VIEWS), "generated views"
        )
        for view in POLICY_VIEWS:
            _sha(views[view], f"generated {view} SHA")
    return {
        **outcome,
        "outcome_path": relative,
        "outcome_sha256": sha256_file(outcome_path),
    }


def publish_case_outcome(
    root: str | Path,
    *,
    contract_path: str | Path,
    role: str,
    seed: int,
    source: str | Path,
    output: str | Path,
    expected_attempt: int | None = None,
) -> dict[str, Any]:
    """Validate an attempt outcome and immutably publish its canonical copy."""

    root = _campaign_root(root)
    contract = load_contract(root, contract_path)
    if contract["schema"] not in {CONTRACT_SCHEMA, PRODUCTION_CONTRACT_SCHEMA}:
        raise EvaluationError("legacy evaluation contracts are diagnostic-only")
    seed = _integer(seed, "seed")
    source_path, _ = _internal_path(root, source, "attempt outcome")
    loaded = load_outcome(
        root,
        source_path,
        contract=contract,
        expected_role=role,
        expected_seed=seed,
        expected_attempt=expected_attempt,
    )
    output_path, output_relative = _internal_path(root, output, "canonical outcome")
    evaluation_root = _evaluation_root_for_contract(
        root, contract["contract_path"], contract["macro_round"]
    )
    expected_output = evaluation_root / "results" / role / f"seed_{seed}" / "outcome.json"
    if output_path != expected_output:
        raise EvaluationError("paired outcome publication path is non-canonical")
    document = load_strict_json(source_path)
    digest = publish_immutable_json(output_path, document)
    return {
        "outcome_path": output_relative,
        "outcome_sha256": digest,
        "image3f_run_id": loaded["image3f_run_id"],
    }


def _mean(values: Sequence[float]) -> float:
    return float(sum(values) / len(values))


def _score(
    parent: Sequence[Mapping[str, Any]],
    candidate: Sequence[Mapping[str, Any]],
    thresholds: Mapping[str, Any],
) -> tuple[dict[str, float], dict[str, Any]]:
    if (
        len(parent) != len(candidate)
        or len(parent) < thresholds["minimum_paired_cases"]
    ):
        raise EvaluationError("paired case count is below the configured minimum")
    for left, right in zip(parent, candidate, strict=True):
        identity = (
            "seed",
            "env_index",
            "scenario_id",
            "first_condition_sha256",
            "first_generated_sha256",
        )
        if any(left[key] != right[key] for key in identity):
            raise EvaluationError("parent/candidate outcomes are not case-paired")
    parent_success = _mean([float(item["success"]) for item in parent])
    candidate_success = _mean([float(item["success"]) for item in candidate])
    parent_safety = _mean([float(item["safety_violation"]) for item in parent])
    candidate_safety = _mean([float(item["safety_violation"]) for item in candidate])
    parent_action = _mean([float(item["action_imitation_mse"]) for item in parent])
    candidate_action = _mean(
        [float(item["action_imitation_mse"]) for item in candidate]
    )
    success_delta = candidate_success - parent_success
    safety_delta = candidate_safety - parent_safety
    action_delta = candidate_action - parent_action
    action_relative_change = action_delta / max(
        parent_action, thresholds["action_mse_floor"]
    )
    meaningful = {
        "success": success_delta >= thresholds["minimum_success_rate_improvement"],
        "safety": -safety_delta >= thresholds["minimum_safety_rate_improvement"],
        "action_imitation": -action_relative_change
        >= thresholds["minimum_action_mse_relative_improvement"],
    }
    nonregression = {
        "success": success_delta >= -thresholds["maximum_success_rate_regression"],
        "safety": safety_delta
        <= thresholds["maximum_safety_violation_rate_regression"],
        "action_imitation": action_relative_change
        <= thresholds["maximum_action_mse_relative_regression"],
    }
    bounded = all(nonregression.values())
    improved = any(meaningful.values())
    passed = bounded and (improved or thresholds["allow_bounded_nonregression"])
    metrics = {
        "paired_cases": float(len(parent)),
        "parent_success_rate": parent_success,
        "candidate_success_rate": candidate_success,
        "paired_success_rate_delta": success_delta,
        "parent_safety_violation_rate": parent_safety,
        "candidate_safety_violation_rate": candidate_safety,
        "paired_safety_violation_rate_delta": safety_delta,
        "parent_action_imitation_mse": parent_action,
        "candidate_action_imitation_mse": candidate_action,
        "paired_action_imitation_mse_delta": action_delta,
        "paired_action_imitation_mse_relative_change": action_relative_change,
        "parent_lag_boundary_cases": float(
            sum(item["episode_length"] > REFERENCE_LAG for item in parent)
        ),
        "candidate_lag_boundary_cases": float(
            sum(item["episode_length"] > REFERENCE_LAG for item in candidate)
        ),
        "paired_initial_condition_matches": float(len(parent)),
        "paired_initial_generated_matches": float(len(parent)),
        "renderer_errors": 0.0,
    }
    decision = {
        "passed": passed,
        "meaningful_improvement": meaningful,
        "bounded_nonregression": nonregression,
        "meaningful_improvement_any": improved,
        "bounded_nonregression_all": bounded,
        "reason_codes": [
            name
            for name, condition in (
                ("SUCCESS_REGRESSION", not nonregression["success"]),
                ("SAFETY_REGRESSION", not nonregression["safety"]),
                ("ACTION_IMITATION_REGRESSION", not nonregression["action_imitation"]),
                ("MEANINGFUL_IMPROVEMENT", improved),
                ("BOUNDED_NONREGRESSION", bounded and not improved),
            )
            if condition
        ],
    }
    return metrics, decision


def summarize_to_evaluator_result(
    root: str | Path,
    *,
    contract_path: str | Path,
    results_dir: str | Path,
    output: str | Path,
) -> dict[str, Any]:
    """Score evidence and emit the immutable orchestrator result.

    This function is intentionally evidence-only: it neither writes a policy
    evaluation nor changes coordinator state.  The output and bundle locations
    are fixed by the production orchestrator contract so a hook cannot redirect
    evidence to an unbound side path.
    """

    root = _campaign_root(root)
    contract = load_contract(root, contract_path)
    if contract["schema"] not in {CONTRACT_SCHEMA, PRODUCTION_CONTRACT_SCHEMA}:
        raise EvaluationError("legacy evaluation contracts are diagnostic-only")
    output_path, output_relative = _internal_path(
        root, output, "orchestrator evaluator result"
    )
    evaluation_root = _evaluation_root_for_contract(
        root, contract["contract_path"], contract["macro_round"]
    )
    expected_output = evaluation_root / "result.json"
    if output_path != expected_output:
        raise EvaluationError("orchestrator evaluator result path is non-canonical")
    results_root, results_relative = _internal_path(
        root, results_dir, "evaluation results"
    )
    expected_results_root = output_path.parent / "results"
    if results_root != expected_results_root:
        raise EvaluationError("paired evaluation results path is non-canonical")
    outcomes: list[dict[str, Any]] = []
    episodes: dict[str, list[dict[str, Any]]] = {"parent": [], "candidate": []}
    for role in ("parent", "candidate"):
        for seed in contract["seeds"]:
            path = results_root / role / f"seed_{seed}" / "outcome.json"
            outcome = load_outcome(
                root,
                path,
                contract=contract,
                expected_role=role,
                expected_seed=seed,
            )
            outcomes.append(
                {
                    "role": role,
                    "seed": seed,
                    "path": outcome["outcome_path"],
                    "sha256": outcome["outcome_sha256"],
                }
            )
            episodes[role].extend(outcome["episodes"])
    metrics, decision = _score(
        episodes["parent"], episodes["candidate"], contract["thresholds"]
    )
    report = {
        "schema": REPORT_SCHEMA,
        "contract_sha256": contract["contract_sha256"],
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "paired_case_count": len(episodes["parent"]),
        "thresholds": contract["thresholds"],
        "metrics": metrics,
        "decision": decision,
        "outcomes": outcomes,
    }
    report_path = results_root / "paired_report.json"
    report_sha = publish_immutable_json(report_path, report)
    bundle = {
        "schema": BUNDLE_SCHEMA,
        "contract_path": contract["contract_path"],
        "contract_sha256": contract["contract_sha256"],
        "report_path": report_path.relative_to(root).as_posix(),
        "report_sha256": report_sha,
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "outcomes": outcomes,
    }
    bundle_path = results_root / "evaluation_bundle.json"
    bundle_sha = publish_immutable_json(bundle_path, bundle)
    bundle_relative = bundle_path.relative_to(root).as_posix()
    evaluator_result = {
        "schema": EVALUATOR_RESULT_SCHEMA,
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "evaluator_config_sha256": contract["evaluation_config_sha256"],
        "evidence_bundle_path": bundle_relative,
        "evidence_bundle_sha256": bundle_sha,
        "passed": decision["passed"],
        "metrics": metrics,
    }
    result_sha = publish_immutable_json(output_path, evaluator_result)
    return {
        "results_path": results_relative,
        "report": {
            **report,
            "path": report_path.relative_to(root).as_posix(),
            "sha256": report_sha,
        },
        "bundle": {
            **bundle,
            "path": bundle_relative,
            "sha256": bundle_sha,
        },
        "evaluator_result": {
            **evaluator_result,
            "path": output_relative,
            "sha256": result_sha,
        },
    }


def verify_evaluator_result_evidence(
    root: str | Path,
    *,
    contract_path: str | Path,
    results_dir: str | Path,
    result_path: str | Path,
) -> dict[str, Any]:
    """Recompute and verify a published evaluator result without writing.

    The orchestrator calls this even when ``result.json`` already exists.  It
    therefore cannot be bypassed by pre-creating a superficially well-formed
    result and a digest-matching opaque bundle: every canonical outcome, its
    source artifacts, the report, bundle, and final result are reloaded and
    deterministically rescored before coordinator state may advance.
    """

    root = _campaign_root(root)
    contract = load_contract(root, contract_path)
    if contract["schema"] not in {CONTRACT_SCHEMA, PRODUCTION_CONTRACT_SCHEMA}:
        raise EvaluationError("legacy evaluation contracts are diagnostic-only")
    output_path, output_relative = _internal_path(
        root, result_path, "orchestrator evaluator result"
    )
    evaluation_root = _evaluation_root_for_contract(
        root, contract["contract_path"], contract["macro_round"]
    )
    expected_output = evaluation_root / "result.json"
    if output_path != expected_output:
        raise EvaluationError("orchestrator evaluator result path is non-canonical")
    results_root, results_relative = _internal_path(
        root, results_dir, "evaluation results"
    )
    if results_root != output_path.parent / "results":
        raise EvaluationError("paired evaluation results path is non-canonical")

    outcomes: list[dict[str, Any]] = []
    episodes: dict[str, list[dict[str, Any]]] = {"parent": [], "candidate": []}
    for role in ("parent", "candidate"):
        for seed in contract["seeds"]:
            outcome = load_outcome(
                root,
                results_root / role / f"seed_{seed}" / "outcome.json",
                contract=contract,
                expected_role=role,
                expected_seed=seed,
            )
            outcomes.append(
                {
                    "role": role,
                    "seed": seed,
                    "path": outcome["outcome_path"],
                    "sha256": outcome["outcome_sha256"],
                }
            )
            episodes[role].extend(outcome["episodes"])
    metrics, decision = _score(
        episodes["parent"], episodes["candidate"], contract["thresholds"]
    )

    expected_report = {
        "schema": REPORT_SCHEMA,
        "contract_sha256": contract["contract_sha256"],
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "paired_case_count": len(episodes["parent"]),
        "thresholds": contract["thresholds"],
        "metrics": metrics,
        "decision": decision,
        "outcomes": outcomes,
    }
    report_path = results_root / "paired_report.json"
    actual_report = _exact(
        load_strict_json(report_path), set(expected_report), "paired evaluation report"
    )
    if actual_report != expected_report:
        raise EvaluationError("paired evaluation report differs from recomputed evidence")
    report_sha = sha256_file(report_path)

    expected_bundle = {
        "schema": BUNDLE_SCHEMA,
        "contract_path": contract["contract_path"],
        "contract_sha256": contract["contract_sha256"],
        "report_path": report_path.relative_to(root).as_posix(),
        "report_sha256": report_sha,
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "anchor_pool": contract["anchor_pool"],
        "outcomes": outcomes,
    }
    bundle_path = results_root / "evaluation_bundle.json"
    actual_bundle = _exact(
        load_strict_json(bundle_path), set(expected_bundle), "evaluation evidence bundle"
    )
    if actual_bundle != expected_bundle:
        raise EvaluationError("evaluation bundle differs from recomputed evidence")
    bundle_sha = sha256_file(bundle_path)

    expected_result = {
        "schema": EVALUATOR_RESULT_SCHEMA,
        "campaign_id": contract["campaign_id"],
        "macro_round": contract["macro_round"],
        "candidate_manifest_sha256": contract["candidate_manifest_sha256"],
        "evaluator_config_sha256": contract["evaluation_config_sha256"],
        "evidence_bundle_path": bundle_path.relative_to(root).as_posix(),
        "evidence_bundle_sha256": bundle_sha,
        "passed": decision["passed"],
        "metrics": metrics,
    }
    actual_result = _exact(
        load_strict_json(output_path), set(expected_result), "evaluator result"
    )
    if actual_result != expected_result:
        raise EvaluationError("evaluator result differs from recomputed evidence")
    return {
        **actual_result,
        "path": output_relative,
        "sha256": sha256_file(output_path),
        "results_path": results_relative,
        "report_sha256": report_sha,
        "evidence_bundle_sha256": bundle_sha,
    }


def _digest_argument(value: str) -> str:
    path = Path(value).expanduser()
    if path.is_file():
        return sha256_file(path)
    if _SHA_RE.fullmatch(value):
        return value
    raise argparse.ArgumentTypeError("expected a regular file or lowercase SHA-256")


