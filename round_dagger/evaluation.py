def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "prepare":
            scenarios = load_strict_json(args.scenario_cases)
            thresholds = load_strict_json(args.thresholds) if args.thresholds else None
            result = create_contract(
                args.root,
                candidate_manifest=args.candidate_manifest,
                scenario_cases=scenarios,
                parent_runtime_policy_sha256=args.parent_runtime_policy_sha256,
                candidate_runtime_policy_sha256=args.candidate_runtime_policy_sha256,
                renderer_runtime_sha256=args.renderer_runtime_sha256,
                evaluation_config_sha256=args.evaluation_config,
                evaluator_code_sha256=args.evaluator_code,
                expected_renderer_count=args.expected_renderer_count,
                anchor_pool_path=args.anchor_pool_path,
                anchor_count=args.anchor_count,
                anchor_index=args.anchor_index,
                anchor_inventory_sha256=args.anchor_inventory_sha256,
                output=args.output,
                thresholds=thresholds,
            )
        elif args.command == "verify-contract":
            result = load_contract(args.root, args.contract)
        elif args.command == "list-cases":
            contract = load_contract(args.root, args.contract)
            for policy in contract["policies"]:
                for seed in contract["seeds"]:
                    print(
                        "\t".join(
                            (
                                policy["role"],
                                str(seed),
                                policy["checkpoint_path"],
                                policy["checkpoint_sha256"],
                                policy["runtime_policy_sha256"],
                            )
                        )
                    )
            return 0
        elif args.command == "run-id":
            contract = load_contract(args.root, args.contract)
            print(
                evaluation_run_id(
                    contract,
                    role=args.role,
                    seed=args.seed,
                    attempt=args.attempt,
                )
            )
            return 0
        elif args.command == "attest":
            result = attest_outcome(
                args.root,
                contract_path=args.contract,
                role=args.role,
                seed=args.seed,
                metrics_path=args.metrics,
                renderer_before_path=args.renderer_before,
                renderer_after_path=args.renderer_after,
                image3f_run_id=args.image3f_run_id,
                output=args.output,
            )
        elif args.command == "verify-outcome":
            contract = load_contract(args.root, args.contract)
            result = load_outcome(
                args.root,
                args.outcome,
                contract=contract,
                expected_role=args.role,
                expected_seed=args.seed,
                expected_attempt=args.expected_attempt,
            )
        elif args.command == "publish-outcome":
            result = publish_case_outcome(
                args.root,
                contract_path=args.contract,
                role=args.role,
                seed=args.seed,
                source=args.source,
                output=args.output,
                expected_attempt=args.expected_attempt,
            )
        elif args.command == "summarize":
            result = summarize_to_evaluator_result(
                args.root,
                contract_path=args.contract,
                results_dir=args.results_dir,
                output=args.output,
            )
        elif args.command == "verify-result":
            result = verify_evaluator_result_evidence(
                args.root,
                contract_path=args.contract,
                results_dir=args.results_dir,
                result_path=args.result,
            )
        else:
            bundle = evaluator_source_bundle(
                args.repository_root,
                args.gr00t_root,
                args.evaluation_source_inventory_sha256,
            )
            result = {
                **bundle,
                "sha256": canonical_json_sha256(bundle),
            }
    except (EvaluationError, ArtifactError, OSError, ValueError) as exc:
        print(f"paired evaluation failed: {exc}", file=__import__("sys").stderr)
        return 2
    print(json.dumps(result, sort_keys=True, indent=2, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
