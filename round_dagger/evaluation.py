"""Strict paired fixed-seed evaluation for round-based local-actor DAgger.

The evaluator compares the frozen active parent and its staged candidate on an
identical, explicit set of ``(seed, environment, scenario_id)`` cases.  Every
policy observation must be generated by the three-view RoboRender path with a
256-frame reference lag.  Raw evaluator and renderer evidence is normalized
into immutable outcome manifests, then scored as paired success, safety, and
expert-action imitation deltas.

The evaluator never mutates coordinator state and never publishes a policy
evaluation.  It emits the immutable result consumed by
:class:`round_dagger.orchestration.MacroRoundOrchestrator`, plus a
content-addressed evidence bundle containing the protocol, every outcome, and
the scored report.  The orchestrator alone publishes the policy evaluation and
advances coordinator state.
"""

